import { chromium } from '@playwright/test'
import { writeFile } from 'node:fs/promises'

const url = process.env.CIVIC_URL || 'http://127.0.0.1:4173/civic/'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'America/Los_Angeles' })
await context.addInitScript(() => {
  window.__civicStorageWrites = []
  const original = Storage.prototype.setItem
  Storage.prototype.setItem = function (key, value) {
    window.__civicStorageWrites.push(key)
    return original.call(this, key, value)
  }
})
const page = await context.newPage()
const results = [], errors = [], nonReadRequests = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (!['GET', 'HEAD', 'OPTIONS'].includes(request.method())) nonReadRequests.push({ method: request.method(), url: request.url() }) })
const check = (group, name, passed) => {
  results.push({ group, name, passed: Boolean(passed) })
  if (!passed) throw new Error(`${group}: ${name}`)
}
const isFocused = locator => locator.evaluate(element => element === document.activeElement)
const focusFrame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
const button = name => page.getByRole('button', { name, exact: true })
const nameField = page.locator('input[name="name"]')
const emailField = page.locator('input[name="email"]')
const dateField = page.locator('input[name="date"]')
const serviceField = page.locator('select[name="service"]')
const timeField = page.locator('select[name="time"]')
const acknowledgement = page.locator('input[name="acknowledge"]')
const resultCount = () => page.locator('.service-card').count()

try {
  // Singapore / Shanghai are already Nov 18, while the browser is still Nov 17.
  await page.clock.setFixedTime(new Date('2026-11-17T16:30:00Z'))
  await page.goto(url)
  check('timezone', 'browser calendar is Nov 17 in Los Angeles', await page.evaluate(() => new Intl.DateTimeFormat('en-CA', { year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date())) === '2026-11-17')
  check('timezone', 'form min is Nov 18 in UTC+8 city time', await dateField.getAttribute('min') === '2026-11-18')
  check('discovery', 'all six services initially visible', await resultCount() === 6)
  await button('生活服务').click()
  check('discovery', 'life category has two results', await resultCount() === 2)
  await page.getByRole('searchbox').count().then(async count => {
    // This search uses a labelled text input, not input type=search.
    if (count !== 0) throw new Error('Unexpected searchbox selector drift')
  })
  await page.getByRole('textbox', { name: '搜索城市服务' }).fill('公共交通')
  check('discovery', 'description search and category intersect to mobility', await resultCount() === 1 && await page.locator('.service-card h3').innerText() === '绿色出行')
  await button('教育文化').click()
  check('discovery', 'incompatible category produces explicit empty state', await resultCount() === 0 && await page.getByRole('heading', { name: '暂时没有找到这项服务' }).isVisible())
  await button('查看全部服务').click()
  await focusFrame()
  check('focus', 'empty-state reset clears query and category', await resultCount() === 6 && await page.locator('#city-search').inputValue() === '' && await button('全部服务').getAttribute('aria-pressed') === 'true')
  check('focus', 'empty-state reset focuses #services', await isFocused(page.locator('#services')))
  await page.locator('#city-search').fill('健康')
  await button('查找服务').click()
  await focusFrame()
  check('focus', 'search submit focuses results with matching health card', await isFocused(page.locator('#services')) && await resultCount() === 1)
  await button('清除搜索 ×').click()
  await focusFrame()
  check('focus', 'clear search restores focus to #city-search', await isFocused(page.locator('#city-search')) && await resultCount() === 6)
  await button('公共课堂').click()
  await focusFrame()
  check('discovery', 'quick link resets category and searches learning', await resultCount() === 1 && await page.locator('.service-card h3').innerText() === '学习与成长')
  await page.locator('.service-card').click()
  await focusFrame()
  check('focus', 'service card prefills selection and focuses select', await serviceField.inputValue() === 'learning' && await isFocused(serviceField))
  await button('健康咨询').click()
  await focusFrame()
  check('focus', 'health shortcut prefills and focuses appointment', await serviceField.inputValue() === 'health' && await isFocused(serviceField))

  await button('生成演示预约').click()
  check('validation', 'native required stops empty name and focuses it', await isFocused(nameField) && await nameField.evaluate(element => element.validity.valueMissing) && await page.locator('.booking-success').count() === 0)
  await nameField.fill('演示小林')
  await emailField.fill('invalid-address')
  await dateField.fill('2026-11-18')
  await timeField.selectOption('14:00 – 15:00')
  await acknowledgement.check()
  await button('生成演示预约').click()
  check('validation', 'native email validity rejects malformed address', await emailField.evaluate(element => element.validity.typeMismatch) && await isFocused(emailField) && await page.locator('.booking-success').count() === 0)
  await emailField.fill('resident@example.com')
  await acknowledgement.uncheck()
  await button('生成演示预约').click()
  check('validation', 'acknowledgement is required', await acknowledgement.evaluate(element => element.validity.valueMissing) && await page.locator('.booking-success').count() === 0)
  await acknowledgement.check()
  await dateField.fill('2026-11-17')
  await button('生成演示预约').click()
  check('validation', 'native date min rejects browser-local today that is city yesterday', await dateField.evaluate(element => element.validity.rangeUnderflow) && await page.locator('.booking-success').count() === 0)
  await dateField.evaluate(element => element.removeAttribute('min'))
  await button('生成演示预约').click()
  await focusFrame()
  check('validation', 'submit guard still rejects city-past date when HTML min removed', (await page.getByRole('alert').innerText()).includes('UTC+8') && await dateField.getAttribute('aria-invalid') === 'true')
  check('focus', 'date error receives keyboard focus', await isFocused(page.getByRole('alert')))
  await dateField.fill('2026-11-18')
  check('validation', 'editing clears previous date error', await page.getByRole('alert').count() === 0)
  await timeField.evaluate(element => element.add(new Option('22:00 – 23:00', '22:00 – 23:00')))
  await timeField.selectOption('22:00 – 23:00')
  await button('生成演示预约').click()
  await focusFrame()
  check('validation', 'submit guard rejects an injected unsupported time option', (await page.getByRole('alert').innerText()).includes('有效的服务时段') && await isFocused(page.getByRole('alert')))
  await timeField.selectOption('14:00 – 15:00')
  await nameField.fill('   ')
  await button('生成演示预约').click()
  await focusFrame()
  check('validation', 'submit guard trims and rejects whitespace-only name', (await page.getByRole('alert').innerText()).includes('请填写称呼') && await page.locator('.booking-success').count() === 0)
  await nameField.fill('演示小林')
  await button('生成演示预约').click()
  await focusFrame()
  const confirmation = page.getByRole('region', { name: '本地预约摘要' })
  check('confirmation', 'success region is focused', await confirmation.isVisible() && await isFocused(confirmation))
  const text = await confirmation.innerText()
  check('confirmation', 'summary repeats selected service, city date, time and local-only state', ['健康关怀', '2026-11-18', '14:00 – 15:00', 'UTC+8 城市服务时间', '仅本地确认 · 未发送', '演示小林'].every(value => text.includes(value)))
  check('privacy', 'no storage writes or stored data after confirmation', await page.evaluate(() => window.__civicStorageWrites.length === 0 && localStorage.length === 0 && sessionStorage.length === 0))
  await page.screenshot({ path: 'artifacts/reviews/batch04-civic-confirmation-after.png' })
  await button('重新安排').click()
  await focusFrame()
  check('confirmation', 'reschedule returns to form and focuses service select', await page.locator('.booking-success').count() === 0 && await isFocused(serviceField))
  check('confirmation', 'reschedule retains service but clears personal fields', await serviceField.inputValue() === 'health' && await nameField.inputValue() === '' && await emailField.inputValue() === '' && !await acknowledgement.isChecked())

  const cards = page.locator('.update-card')
  await cards.nth(0).getByRole('button', { name: '阅读更多' }).click()
  check('content', 'announcement expands local-demo activity details', (await cards.nth(0).locator('.update-detail').innerText()).includes('没有实际活动报名') && await cards.nth(0).getByRole('button', { name: '收起详情' }).getAttribute('aria-expanded') === 'true')
  await cards.nth(1).getByRole('button', { name: '阅读更多' }).click()
  check('content', 'opening second announcement closes first', await cards.nth(0).locator('.update-detail').count() === 0 && await cards.nth(1).locator('.update-detail').count() === 1)
  await cards.nth(1).getByRole('button', { name: '收起详情' }).click()
  check('content', 'announcement can collapse', await page.locator('.update-detail').count() === 0)
  await page.getByText('我的信息会保存在哪里？', { exact: true }).click()
  check('content', 'FAQ discloses no storage or server transmission', await page.locator('.faq-list details').last().getAttribute('open') !== null && (await page.locator('.faq-list details').last().innerText()).includes('不写入本地存储'))
  await page.reload()
  check('privacy', 'reload resets confirmation and entered personal data', await page.locator('.booking-success').count() === 0 && await nameField.inputValue() === '' && await emailField.inputValue() === '')

  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 })
    await page.goto(url)
    check('layout', `${width}px viewport has no horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    check('layout', `${width}px header main and form stay within viewport`, await page.locator('.site-header, main, .booking-panel').evaluateAll(elements => elements.every(element => {const rect = element.getBoundingClientRect(); return rect.left >= -1 && rect.right <= innerWidth + 1})))
    if (width !== 1440) {
      await button('打开导航').click()
      const navigation = page.getByRole('navigation', { name: '主导航' })
      check('navigation', `${width}px mobile navigation expands`, await navigation.isVisible() && await button('关闭导航').getAttribute('aria-expanded') === 'true')
      await navigation.getByRole('link', { name: '城市服务', exact: true }).focus()
      await page.keyboard.press('Escape')
      check('navigation', `${width}px Escape closes nav and returns focus`, !await navigation.isVisible() && await isFocused(button('打开导航')))
      await button('打开导航').click()
      await navigation.getByRole('link', { name: '城市动态', exact: true }).click()
      check('navigation', `${width}px choosing destination closes navigation`, !await navigation.isVisible())
    }
    await page.screenshot({ path: `artifacts/reviews/batch04-civic-${width}-after.png`, fullPage: true })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  check('accessibility', 'reduced motion disables smooth document scrolling', await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior === 'auto'))
  await page.locator('#city-search').fill('不存在服务')
  await button('查看全部服务').click()
  await focusFrame()
  check('focus', '320px no-results recovery focuses services in reduced motion', await isFocused(page.locator('#services')) && await resultCount() === 6)
  check('privacy', 'no POST or other mutating network requests', nonReadRequests.length === 0)
  check('runtime', 'no uncaught browser errors', errors.length === 0)
} catch (error) {
  errors.push(String(error))
  await page.screenshot({ path: 'artifacts/reviews/batch04-civic-failure.png', fullPage: true }).catch(() => {})
  process.exitCode = 1
} finally {
  const report = { site: 'civic', target: url, testedAt: new Date().toISOString(), browserTimezone: 'America/Los_Angeles', fixedTime: '2026-11-17T16:30:00Z', passed: results.filter(result => result.passed).length, total: results.length, results, errors, nonReadRequests }
  await writeFile('artifacts/reviews/batch04-civic-results.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify({ passed: report.passed, total: report.total, errors }))
  await browser.close()
}
